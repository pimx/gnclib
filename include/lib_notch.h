//============================================================================
// lib_notch.h -- режекторный фильтр второго порядка с подвижным центром
// (1.6.0).
//
//   H(s) = (s^2 + 2 zz w0 s + w0^2) / (s^2 + 2 zp w0 s + w0^2),
// глубина на w0 -- zz / zp, ширина ~ 2 zp w0. Дискретно: билинейное
// преобразование с предыскажением на w0 (провал остаётся точно на w0 при
// любом такте), прямая форма II транспонированная; коэффициенты считаются
// на каждом такте, так что w0 может меняться от такта к такту.
// C++17, без STL, без кучи, без исключений.
//============================================================================
#ifndef GNCLIB_LIB_NOTCH_H
#define GNCLIB_LIB_NOTCH_H

#include <math.h>

namespace gnc
{

struct Notch
{
    double z1; // состояние прямой формы II транспонированной
    double z2;
};

// Сброс состояния фильтра.
inline void NotchInit(Notch* n)
{
    n->z1 = 0.0;
    n->z2 = 0.0;
}

// Один отсчёт фильтра.
//   x -- вход; w0 -- центр, рад/с; zz, zp -- демпфирование нуля и полюса;
//   dt -- такт, с
// Возвращает выход фильтра; при непригодных такте или частоте (dt <= 0,
// w0 <= 0, w0 dt >= 3) -- вход без изменения.
inline double NotchStep(Notch* n, double x, double w0, double zz, double zp, double dt)
{
    if (dt <= 0.0 || w0 <= 0.0 || w0 * dt >= 3.0)
    {
        return x;
    }
    double K = w0 / tan(0.5 * w0 * dt); // предыскажение: s = K (1 - z^-1) / (1 + z^-1)
    double K2 = K * K;
    double w2 = w0 * w0;
    double a0 = K2 + 2.0 * zp * w0 * K + w2;
    double b0 = (K2 + 2.0 * zz * w0 * K + w2) / a0;
    double b1 = (2.0 * w2 - 2.0 * K2) / a0;
    double b2 = (K2 - 2.0 * zz * w0 * K + w2) / a0;
    double a1 = (2.0 * w2 - 2.0 * K2) / a0;
    double a2 = (K2 - 2.0 * zp * w0 * K + w2) / a0;
    double y = b0 * x + n->z1;
    n->z1 = b1 * x - a1 * y + n->z2;
    n->z2 = b2 * x - a2 * y;
    return y;
}

} // namespace gnc

#endif // GNCLIB_LIB_NOTCH_H
