//============================================================================
// lib_slosh_types.h -- данные модели плескания топлива (1.7.0): описание
// бака, строки и таблицы параметров по заполнению, параметры
// пружинно-массового аналога при текущих заполнении и осевой перегрузке.
//
// Эквивалентная механическая модель (пружинно-массовый аналог). Жидкость
// бака заменяется
//   - НЕПОДВИЖНОЙ массой m0 (поперечный момент инерции I0 относительно
//     своего ЦМ), жёстко связанной с баком, -- она входит в жёсткую часть
//     изделия;
//   - nModes массами плескания m_n на изотропных поперечных пружинах
//     k_n = m_n w_n^2 с демпферами; масса движется в плоскости, нормальной
//     оси бака (2 степени свободы), вдоль оси -- вместе с баком.
// Частоты растут с осевой удельной силой: w_n^2 = |a| * w2a_n; массы и
// положения от |a| не зависят.
//
// Положения вдоль оси бака отсчитываются от ОСЕВШЕГО ДНИЩА: заднего, когда
// осевая удельная сила направлена к носу (a > 0, тяга), переднего при
// a < 0 (торможение без тяги; строка параметров та же -- бак считается
// симметричным по длине).
//
// Соглашения gnclib: связанные оси bu (нос), be (левый борт), bn = bu x be;
// плечи отсчитываются от начала связанной системы (хвост). Ось бака
// параллельна bu. C++17, без STL, без кучи, без исключений.
//============================================================================
#ifndef GNCLIB_LIB_SLOSH_TYPES_H
#define GNCLIB_LIB_SLOSH_TYPES_H

namespace gnc
{

inline constexpr int SLOSH_NMODE = 3;   // тонов на бак (наибольшее)
inline constexpr int SLOSH_NBAFFLE = 8; // кольцевых перегородок на бак
inline constexpr int SLOSH_NROW = 64;   // строк в таблице параметров

//----------------------------------------------------------------------------
// Параметры аналога при одном заполнении, приведённые: массы -- доли массы
// жидкости, положения -- от осевшего днища, частоты -- на единицу |a|.
// m0r, z0, i0r относятся к случаю, когда ВСЕ тоны строки явные (тона с
// mr = 0 нет); бак с меньшим числом тонов присоединяет остальные к
// неподвижной массе (SloshRowToParams).
//----------------------------------------------------------------------------
struct SloshRow
{
    double zSurf = 0.0;                 // свободная поверхность от днища, м
    double zLiq = 0.0;                  // ЦМ жидкости от днища, м
    double m0r = 0.0;                   // неподвижная масса / масса жидкости
    double z0 = 0.0;                    // неподвижная масса от днища, м
    double i0r = 0.0;                   // I0 (поперечный, свой ЦМ) / масса, м^2
    double iRollr = 0.0;                // момент крена ЗАМОРОЖЕННОЙ жидкости / масса, м^2
    double mr[SLOSH_NMODE] = { };       // масса плескания / масса жидкости
    double z[SLOSH_NMODE] = { };        // масса плескания от днища, м
    double w2a[SLOSH_NMODE] = { };      // w^2 / |a| = 1 / длина маятника, 1/м
    double eta[SLOSH_NMODE] = { };      // высота волны у стенки / смещение массы
};

// Таблица строк по возрастающей доле заполнения q (линейно между строками,
// края удерживаются).
struct SloshTable
{
    int n = 0;
    double q[SLOSH_NROW] = { };         // масса жидкости / полная масса
    SloshRow row[SLOSH_NROW] = { };
};

// Кольцевая перегородка: кольцевая пластина, нормальная оси бака.
struct SloshBaffle
{
    double arm = 0.0;                   // плечо пластины по bu от хвоста, м
    double width = 0.0;                 // радиальная ширина кольца, м
};

//----------------------------------------------------------------------------
// Описание бака. Геометрия эквивалентного цилиндра с плоским днищем задаётся
// всегда (радиус -- для демпфирования и числа Бонда, длина -- для
// заполнения); параметры аналога -- из аналитического решения для
// цилиндра (table == 0) или из таблицы потребителя (CFD, справочные
// таблицы для баков со сферическими днищами, сферических баков).
//----------------------------------------------------------------------------
struct SloshTank
{
    double radius = 0.0;                // R, м
    double length = 0.0;                // L, длина цилиндра, м
    double armAft = 0.0;                // плечо заднего днища по bu от хвоста, м
    double offBn = 0.0;                 // поперечное смещение оси бака, bn, м
    double offBe = 0.0;                 // поперечное смещение оси бака, be, м
    double rho = 0.0;                   // плотность жидкости, кг/м^3
    double massFull = 0.0;              // полная масса жидкости, кг (0 -- rho pi R^2 L)
    double nu = 0.0;                    // кинематическая вязкость, м^2/с (0 -- без стенки)
    double sigma = 0.0;                 // поверхностное натяжение, Н/м (0 -- без Бонда)
    int nModes = 1;                     // явных тонов, 1..SLOSH_NMODE
    double zetaFix[SLOSH_NMODE] = { };  // > 0: заданное демпфирование; <= 0: расчётное
    double kRoll = 0.0;                 // доля момента крена замороженной жидкости, 0..1
    int nBaffle = 0;                    // кольцевых перегородок, 0..SLOSH_NBAFFLE
    SloshBaffle baffle[SLOSH_NBAFFLE] = { };
    const SloshTable* table = 0;        // 0 -- аналитика цилиндра с плоским днищем
};

//----------------------------------------------------------------------------
// Параметры при текущих заполнении и осевой удельной силе
// (SloshModel::Update). Плечи -- абсолютные по bu от хвоста, в покое.
//----------------------------------------------------------------------------
struct SloshModeParams
{
    double m = 0.0;                     // масса плескания, кг
    double w = 0.0;                     // собственная частота (бак отдельно), рад/с
    double k = 0.0;                     // жёсткость пружины m w^2, Н/м
    double zeta0 = 0.0;                 // демпфирование, не зависящее от амплитуды
    double arm = 0.0;                   // плечо массы в покое по bu, м
    double lPend = 0.0;                 // длина эквивалентного маятника |a| / w^2, м
    double eta = 0.0;                   // высота волны у стенки / смещение массы
};

struct SloshTankParams
{
    double mL = 0.0;                    // масса жидкости, кг
    double q = 0.0;                     // доля заполнения mL / massFull
    double a = 0.0;                     // использованная осевая удельная сила, м/с^2
    double sgn = 1.0;                   // +1: осела у заднего днища, -1: у переднего
    double armSurf = 0.0;               // плечо свободной поверхности по bu, м
    double armLiq = 0.0;                // плечо ЦМ жидкости по bu, м
    double m0 = 0.0;                    // неподвижная масса, кг
    double arm0 = 0.0;                  // плечо неподвижной массы по bu, м
    double i0 = 0.0;                    // поперечный момент неподвижной части, свой ЦМ, кг м^2
    double iRoll = 0.0;                 // момент крена неподвижной части (kRoll * замороженный)
    double bond = 0.0;                  // число Бонда rho |a| R^2 / sigma (0 при sigma = 0)
    int valid = 0;                      // 1: |a| и число Бонда в пределах модели
    int nModes = 0;                     // явных тонов
    SloshModeParams mode[SLOSH_NMODE] = { };
};

// Состояние одного тона для телеметрии (SloshModel::ModeState).
struct SloshModeState
{
    double xiBn = 0.0;                  // смещение массы от покоя, bn, м
    double xiBe = 0.0;                  // смещение, be, м
    double vBn = 0.0;                   // скорость относительно бака, bn, м/с
    double vBe = 0.0;                   // скорость относительно бака, be, м/с
    double amp = 0.0;                   // амплитуда sqrt(xi^2 + v^2 / w^2), м
    double wave = 0.0;                  // высота волны у стенки eta * amp, м
    double zeta = 0.0;                  // действующее демпфирование (с перегородками)
};

} // namespace gnc

#endif // GNCLIB_LIB_SLOSH_TYPES_H
