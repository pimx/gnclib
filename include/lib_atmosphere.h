/* lib_atmosphere.h -- послойная стандартная атмосфера (US Standard 1976).
 *
 * class Atmosphere инкапсулирует модель атмосферной среды: температура,
 * статическое давление, плотность, скорость звука, число Маха, скоростной
 * напор как функции геометрической высоты. Послойная модель (тропосфера --
 * нижняя мезосфера), валидна до ~86 км; выше давление/плотность обнуляются.
 * Высота трактуется как геометрическая (ошибка <0.5% ниже 50 км) --
 * достаточно для сопротивления и противодавления двигателя; для строгих
 * расчётов даны преобразования геометрическая <-> геопотенциальная.
 *
 * Расширения сверх базовой модели:
 *   - отклонение температуры от ISA (dTemp): горячий/холодный день --
 *     температура сдвигается, давление послойное сохраняется, плотность
 *     пересчитывается по уравнению состояния;
 *   - динамическая вязкость (Сазерленд), кинематическая вязкость,
 *     число Рейнольдса.
 *
 * Класс сделан экземплярным (а не набором свободных функций), чтобы за тем
 * же интерфейсом можно было подменить альтернативную атмосферу (Марс,
 * рассеянные горячий/холодный день). Один общий экземпляр обслуживает все
 * модули. Без STL, без исключений, без динамических аллокаций.
 */
#ifndef LIB_ATMOSPHERE_H
#define LIB_ATMOSPHERE_H

class Atmosphere
{
public:
    /* Опорное давление на уровне моря [Па]. */
    static const double P_SL;

    /* dTemp -- сдвиг температуры от ISA [K] (0 -- стандартный день). */
    explicit Atmosphere(double dTemp = 0.0);

    /* Установка/чтение отклонения от ISA [K]. */
    void setDeltaTemp(double dTemp)
    {
        m_dTemp = dTemp;
    }
    double deltaTemp() const
    {
        return m_dTemp;
    }

    /* Температура воздуха [K] на геометрической высоте h [м]; ниже 0 м
     * клампится; выше 86 км константа 186 K. Учитывает dTemp. */
    double temperature(double h) const;

    /* Статическое давление [Па]: гидростатическое интегрирование в слое;
     * 0 выше 86 км. НЕ зависит от dTemp (соглашение "давление постоянно,
     * температура сдвинута" для нестандартного дня). */
    double pressure(double h) const;

    /* Плотность воздуха [кг/м^3] из уравнения состояния rho = P/(R T);
     * 0 выше 86 км. Учитывает dTemp через температуру. */
    double density(double h) const;

    /* Отношение давления к уровню моря, кламп [0,1]; для модели движка. */
    double pressureRatio(double h) const;

    /* Скорость звука [м/с]: a = sqrt(gamma R T), gamma = 1.4. */
    double soundSpeed(double h) const;

    /* Число Маха для воздушной скорости V [м/с] на высоте h [м]. */
    double mach(double h, double V) const;

    /* Скоростной напор q = 1/2 rho V^2 [Па]. */
    double dynamicPressure(double h, double V) const;

    /* Динамическая вязкость по Сазерленду [Па*с]:
     * mu = 1.458e-6 T^1.5 / (T + 110.4). */
    double dynamicViscosity(double h) const;

    /* Кинематическая вязкость nu = mu/rho [м^2/с]; 0 при rho = 0. */
    double kinematicViscosity(double h) const;

    /* Число Рейнольдса по характерному размеру L [м] и скорости V [м/с];
     * 0 при вырождении вязкости. */
    double reynolds(double h, double V, double L) const;

    /* Геометрическая -> геопотенциальная высота: H = Re h / (Re + h). */
    static double geometricToGeopotential(double h);

    /* Геопотенциальная -> геометрическая высота: h = Re H / (Re - H). */
    static double geopotentialToGeometric(double H);

private:
    /* Слой кусочной модели: базовая высота, базовая температура,
     * градиент, базовое давление. */
    struct Layer
    {
        double h_b, T_b, L_b, P_b;
    };
    enum
    {
        N_LAYERS = 7
    };
    Layer m_layers[N_LAYERS];
    double m_dTemp; /* сдвиг температуры от ISA, K */

    /* Индекс слоя, содержащего высоту h (h уже клампирована >= 0). */
    int layerIndex(double h) const;

    /* Температура ISA без сдвига (внутренняя, для давления). */
    double temperatureIsa(double h) const;
};

#endif /* LIB_ATMOSPHERE_H */
