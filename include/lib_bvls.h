//============================================================================
// lib_bvls.h -- наименьшие квадраты с границами переменных (1.7.0):
//   min || A x - b ||,  lb <= x <= ub,
// методом активного набора (прямой метод, как у распределения органов
// управления WLS). Подзадача на свободных переменных решается
// преобразованиями Хаусхолдера (QR), без нормальных уравнений.
//
// Требование: столбцы A, соответствующие свободным переменным, линейно
// независимы (у распределителя это обеспечивают строки регуляризации).
// Переменная с ub - lb <= 1e-15 (1 + |lb|) закреплена на lb и не
// освобождается. Тёплый старт: начальное x ограничивается границами,
// переменные на границах входят в активный набор.
// C++17, без STL, без кучи (объект ~26 КБ).
//============================================================================
#ifndef GNCLIB_LIB_BVLS_H
#define GNCLIB_LIB_BVLS_H

namespace gnc
{

enum
{
    BVLS_MAX_ROWS = 64, // предел числа строк A
    BVLS_MAX_COLS = 48  // предел числа переменных
};

// Состояние переменной после решения
enum BvlsState
{
    BVLS_FREE = 0,   // внутри границ
    BVLS_LOWER = -1, // на нижней границе
    BVLS_UPPER = 1,  // на верхней границе
    BVLS_FIXED = 2   // закреплена (lb == ub)
};

class Bvls
{
public:
    Bvls();

    // Решение. Возврат: число итераций (>= 1); -1 -- предел итераций
    // исчерпан (x -- последняя допустимая точка); -2 -- неверные
    // размеры либо вырожденная подзадача (x допустимо, но не оптимально).
    //   A -- матрица m x n построчно (A[i * n + j]); b -- правая часть (m);
    //   m, n -- размеры (n <= m); lb, ub -- границы (n); x -- начальное
    //   приближение и результат (n); maxIter -- предел итераций
    int solve(const double* A, const double* b, int m, int n,
              const double* lb, const double* ub, double* x, int maxIter);

    // Состояние переменной j после решения (BvlsState)
    int state(int j) const
    {
        return m_state[j];
    }

    // Число переменных на границах (без закреплённых)
    int boundCount() const;

private:
    // Решение подзадачи на свободных переменных: m_z[k] -- значение
    // свободной переменной m_free[k]. Возврат: false -- вырождена.
    bool subproblem(const double* A, const double* b, int m, int n, const double* x);

    // Множители Лагранжа активных переменных; возврат -- номер переменной
    // с наибольшим по модулю отрицательным множителем либо -1.
    int worstMultiplier(const double* A, const double* b, int m, int n,
                        const double* x, double tol) const;

    double m_W[BVLS_MAX_ROWS * BVLS_MAX_COLS]; // столбцы свободных переменных
    double m_r[BVLS_MAX_ROWS];                 // правая часть подзадачи
    double m_u[BVLS_MAX_ROWS];                 // вектор Хаусхолдера
    double m_z[BVLS_MAX_COLS];                 // решение подзадачи
    int m_free[BVLS_MAX_COLS];                 // номера свободных переменных
    int m_nFree;                               // число свободных
    int m_state[BVLS_MAX_COLS];                // состояния переменных
    int m_n;                                   // число переменных
};

} // namespace gnc

#endif // GNCLIB_LIB_BVLS_H
