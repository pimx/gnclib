//============================================================================
// lib_engine_model.h -- модель объекта силовой установки (1.7.0): от команд
// дросселей и сервоприводов к фактическим положениям органов и силовым
// характеристикам (lib_engine.h).
//
// Дроссель на шаге dt модели:
//   команда -> запаздывание (целое число шагов, round(delay / dt)) ->
//   ограничение диапазоном -> звено 1-го порядка (если tau > 0) ->
//   предел скорости (rate * dt за шаг) -> фактическое положение.
// Сервопривод:
//   команда -> запаздывание -> ограничение пределами и конусом ->
//   либо звено 1-го порядка и предел скорости (wn = 0),
//   либо звено 2-го порядка wn, zeta с пределом скорости (wn > 0; подшаги
//   h <= 0.05 / wn) -> фактическое положение, удерживаемое в пределах и
//   (два привода) в конусе; на упоре скорость наружу гасится.
// При tau = 0, wn = 0 и шаге команды не больше rate * dt фактическое
// положение равно команде, задержанной на целое число шагов, побитно.
//
// Включение и выключение сопла -- setOn. При startRate > 0 включённое
// сопло набирает дроссель от нуля (или от уровня догорания) с этим темпом
// до команды; при shutdownRate > 0 выключенное сопло догорает: его дроссель
// спадает до нуля с этим темпом, тяга и расход есть, пока он не ноль.
// Разброс тяги и перекос сопел (NozzleConfig::thrustFactor, misalign)
// учитываются только здесь; распределитель (lib_engine_alloc.h) их не
// знает. Сила постоянна на шаге модели; интегрирование движения аппарата --
// у потребителя. C++17, без STL, без кучи (объект ~50 КБ -- объявлять static).
//============================================================================
#ifndef GNCLIB_LIB_ENGINE_MODEL_H
#define GNCLIB_LIB_ENGINE_MODEL_H

#include "lib_engine.h"

namespace gnc
{

class EngineModel
{
public:
    EngineModel();

    // Инициализация. Описание не копируется (время жизни -- у вызывающего).
    // Возврат: false -- описание негодно, шаг не положителен или
    // запаздывание не меньше ENGINE_DELAY_MAX шагов.
    //   cfg -- описание установки; dt -- шаг модели, с
    bool init(const EngineConfig* cfg, double dt);

    // Начальное состояние: все сопла работают, дроссели throttle (в
    // диапазоне), углы нулевые, приводы в покое; линии запаздывания
    // заполнены этим состоянием.
    //   throttle -- начальный дроссель
    void reset(double throttle);

    // Начальное состояние по заданным положениям органов (ограничиваются
    // пределами); все сопла работают, линии запаздывания заполнены ими.
    //   x -- положения органов
    void reset(const EngineCommand& x);

    // Включение или выключение (отказ) сопла.
    //   i -- номер сопла; on -- true работает; immediate -- без нарастания
    //   и догорания (начальная расстановка сопел)
    void setOn(int i, bool on, bool immediate = false);

    // Шаг модели: команда поступает в линии запаздывания, органы
    // отрабатывают задержанную команду.
    //   cmd -- команды органов
    void step(const EngineCommand& cmd);

    // Силовые характеристики по фактическим положениям органов (с
    // разбросом, перекосом и догоранием выключенных сопел).
    //   pa -- давление среды, Па; point -- точка приведения момента;
    //   out -- результат
    void forces(double pa, const CfBodyVector& point, EngineForces* out) const;

    // Фактические положения органов (дроссель выключенного сопла -- его
    // отработка команды; действующий дроссель -- throttleOut)
    const EngineCommand& actual() const
    {
        return m_act;
    }

    // Действующий дроссель сопла: работающего -- фактический, выключенного --
    // уровень догорания (0 -- погасло).
    //   i -- номер сопла
    double throttleOut(int i) const
    {
        return m_on[i] ? m_act.throttle[i] : m_level[i];
    }

    // Признаки работы сопел (1 -- работает)
    const unsigned char* on() const
    {
        return m_on;
    }

    // Запаздывание дросселя и сервоприводов сопла i, шагов модели
    int delayThrottleSteps() const
    {
        return m_nThr;
    }
    int delayServoSteps(int i) const
    {
        return m_nSrv[i];
    }

private:
    // Отработка органа звеном 1-го порядка и пределом скорости.
    //   x -- текущее положение; target -- задержанная ограниченная команда;
    //   rate -- предел скорости (<= 0 -- нет); alpha -- доля звена за шаг
    //   (1 -- звена нет). Возврат: новое положение
    double follow(double x, double target, double rate, double alpha) const;

    // Отработка угла звеном 2-го порядка с пределом скорости и упором.
    //   n -- сопло; x, v -- угол и его скорость (вход и выход);
    //   target -- задержанная ограниченная команда; limit -- упор, рад
    void servo2(const NozzleConfig& n, double* x, double* v, double target, double limit) const;

    // Отработка углов сопла i на шаге по задержанной команде cs.
    void servoStep(int i, const EngineCommand& cs);

    // Отработка дросселя сопла i на шаге по задержанной команде ct.
    void throttleStep(int i, const EngineCommand& ct);

    // Задержанная команда n шагов назад
    const EngineCommand& delayed(int n) const;

    const EngineConfig* m_cfg;                 // описание
    double m_dt;                               // шаг, с
    int m_nThr;                                // запаздывание дросселя, шагов
    int m_nSrv[ENGINE_MAX_NOZZLES];            // запаздывание приводов, шагов
    double m_aThr;                             // доля звена дросселя за шаг
    double m_aSrv[ENGINE_MAX_NOZZLES];         // доля звена приводов за шаг
    EngineCommand m_ring[ENGINE_DELAY_MAX];    // линия запаздывания команд
    int m_head;                                // последняя записанная команда
    EngineCommand m_act;                       // фактические положения
    double m_v1[ENGINE_MAX_NOZZLES];           // скорости углов d1 (2-й порядок), рад/с
    double m_v2[ENGINE_MAX_NOZZLES];           // скорости углов d2, рад/с
    double m_level[ENGINE_MAX_NOZZLES];        // дроссель догорания выключенного сопла
    unsigned char m_starting[ENGINE_MAX_NOZZLES]; // 1 -- сопло набирает дроссель после включения
    unsigned char m_on[ENGINE_MAX_NOZZLES];    // признаки работы сопел
};

} // namespace gnc

#endif // GNCLIB_LIB_ENGINE_MODEL_H
