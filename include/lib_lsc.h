//============================================================================
// lib_lsc.h -- наименьшие квадраты с границами переменных и линейными
// ограничениями на пары переменных (1.7.0):
//   min || A x - b ||,  lb <= x <= ub,  a1 x_j + a2 x_k <= h  (пары (j, k)),
// методом активного набора (прямой метод, обобщение lib_bvls.h). Каждая
// переменная входит не более чем в одну пару; ограничения пары связывают
// только её две переменные. Рабочий набор пары -- не больше двух
// независимых ограничений: одно -- пара движется по прямой ограничения
// (одна свободная переменная вдоль прямой), два -- пара закреплена в
// вершине. Подзадача на свободных переменных решается преобразованиями
// Хаусхолдера (QR), без нормальных уравнений.
//
// Требования: столбцы A линейно независимы (у распределителя это
// обеспечивают строки регуляризации); начальное x допустимо по
// ограничениям пар (границы оно соблюдать не обязано -- ограничивается
// ими). Переменная с ub - lb <= 1e-15 (1 + |lb|) закреплена на lb. Тёплый
// старт: ограничения, выполненные в начальной точке как равенства (с
// допуском), входят в рабочий набор.
// Назначение: конус сопла с двумя приводами в распределителе
// (lib_engine_alloc.h) -- выпуклая область, заменяемая касательными
// (отсекающими) прямыми.
// C++17, без STL, без кучи (объект ~70 КБ -- объявлять static).
//============================================================================
#ifndef GNCLIB_LIB_LSC_H
#define GNCLIB_LIB_LSC_H

namespace gnc
{

enum
{
    LSC_MAX_ROWS = 64,  // предел числа строк A
    LSC_MAX_COLS = 48,  // предел числа переменных
    LSC_MAX_CUTS = 1024 // предел числа ограничений пар, всего
};

class Lsc
{
public:
    Lsc();

    // Новая задача: число переменных и границы; пары и их ограничения
    // сбрасываются. Возврат: false -- неверное n.
    //   n -- число переменных; lb, ub -- границы (n)
    bool setup(int n, const double* lb, const double* ub);

    // Пара переменных j, k (обе ещё не в парах). Возврат: номер пары либо -1.
    //   j, k -- переменные
    int pair(int j, int k);

    // Ограничение пары p: a1 x_j + a2 x_k <= h (j, k -- в порядке вызова
    // pair); нормируется на |(a1, a2)|. Возврат: false -- предел числа
    // ограничений либо нулевая нормаль.
    //   p -- пара; a1, a2, h -- ограничение
    bool cut(int p, double a1, double a2, double h);

    // Решение. Возврат: число итераций (>= 1); -1 -- предел итераций
    // исчерпан (x -- последняя допустимая точка); -2 -- неверные размеры
    // либо вырожденная подзадача; -3 -- начальная точка нарушает
    // ограничение пары (x не изменено).
    //   A -- матрица m x n построчно (A[i * n + j]); b -- правая часть (m);
    //   m -- число строк (n <= m); x -- начальное приближение и результат (n);
    //   maxIter -- предел итераций
    int solve(const double* A, const double* b, int m, double* x, int maxIter);

    // Число ограничений пар
    int cuts() const
    {
        return m_nc;
    }

    // Число ограничений в рабочем наборе после решения (без закреплённых
    // переменных)
    int activeCount() const;

private:
    // Ограничение id в координатах группы g: a0 x_g0 + a1 x_g1 <= h.
    // id < 2 n -- граница переменной id / 2 (чётный -- нижняя), иначе
    // ограничение пары id - 2 n.
    void row(int id, double* a0, double* a1, double* h) const;
    // Рабочий набор из ограничений, выполненных в x как равенства
    void startSet(const double* x);
    // Можно ли добавить ограничение id в рабочий набор группы g
    bool independent(int g, int id) const;
    // Подзадача: значения переменных при рабочем наборе (m_xs); точки
    // прямых и вершин -- поправками к текущему x (почти параллельные
    // ограничения: правило Крамера в абсолютных величинах теряет точность)
    bool subproblem(const double* A, const double* b, int m, const double* x);
    // Множители рабочего набора; возврат -- (группа, позиция) наихудшего
    // отрицательного либо -1
    int worstMultiplier(const double* A, const double* b, int m, const double* x,
                        double tol) const;

    int m_n;                          // число переменных
    double m_lb[LSC_MAX_COLS];        // границы
    double m_ub[LSC_MAX_COLS];
    unsigned char m_fix[LSC_MAX_COLS]; // 1 -- переменная закреплена
    int m_grp[LSC_MAX_COLS];          // группа переменной
    int m_ng;                         // число групп
    int m_gv[LSC_MAX_COLS][2];        // переменные группы (вторая -1 -- одиночная)
    int m_ws[LSC_MAX_COLS][2];        // рабочий набор группы (номера ограничений)
    int m_wn[LSC_MAX_COLS];           // размер рабочего набора группы
    int m_first[LSC_MAX_COLS];        // первое ограничение пары группы (-1 -- нет)
    int m_nc;                         // число ограничений пар
    int m_cg[LSC_MAX_CUTS];           // группа ограничения
    int m_next[LSC_MAX_CUTS];         // следующее ограничение той же группы
    int m_last[LSC_MAX_COLS];         // последнее ограничение пары группы
    double m_ca[LSC_MAX_CUTS][2];     // нормаль (единичная)
    double m_ch[LSC_MAX_CUTS];        // правая часть
    double m_xs[LSC_MAX_COLS];        // решение подзадачи
    double m_W[LSC_MAX_ROWS * LSC_MAX_COLS]; // столбцы свободных переменных
    double m_r[LSC_MAX_ROWS];         // правая часть подзадачи
    double m_u[LSC_MAX_ROWS];         // вектор Хаусхолдера
    double m_z[LSC_MAX_COLS];         // решение подзадачи (свободные)
    int m_fg[LSC_MAX_COLS];           // группа свободной переменной
    double m_ft[LSC_MAX_COLS][2];     // направление свободной переменной в группе
};

} // namespace gnc

#endif // GNCLIB_LIB_LSC_H
