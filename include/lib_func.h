// общего назначения).
//
// clampd(v, lo, hi) -- ограничение значения диапазоном [lo, hi].
// ВНИМАНИЕ: макрос; аргументы могут вычисляться БОЛЕЕ ОДНОГО РАЗА --
// не передавать выражения с побочными эффектами (инкременты, вызовы
// функций с состоянием). Чистые выражения (арифметика, чистые методы)
// допустимы.
//============================================================================
#ifndef LIB_FUNC_H
#define LIB_FUNC_H

// Ограничение значения диапазоном [lo, hi]
#define clampd(v, lo, hi) (((v) < (lo)) ? (lo) : (((v) > (hi)) ? (hi) : (v)))

#endif // LIB_FUNC_H
