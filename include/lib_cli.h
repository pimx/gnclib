//============================================================================
// lib_cli.h -- библиотечный разбор командной строки.
//
// Класс Cli: инициализация аргументами main (argc/argv; строки НЕ
// копируются -- время жизни argv покрывает программу), далее запросы:
//   hasKey("wind")            -- наличие ключа (флажка);
//   getKeyValue("wind", buf)  -- значение ключа (default, если не задано);
//   getPosValue(2, buf)       -- позиционный аргумент по индексу.
//
// СИНТАКСИС аргументов:
//   -key value      значение -- следующий токен (если он не ключ);
//   /key=value      значение после '=' (форма /key value также принята);
//   позиционные     обычные токены через пробелы.
// Признак ключа: токен начинается с '-' или '/', далее ПЕРВЫЙ символ имени --
// БУКВА, остальные -- БУКВЫ ИЛИ ЦИФРЫ (до '=' или конца). Поэтому
// отрицательные числа ("-2.0") остаются значениями, пути ("/tmp/app") и
// токены с иными символами в имени ("/data.2=x") -- позиционными аргументами,
// а имена вида "prop0" и "kv2" -- полноценными ключами (правка по требованию
// владельца: ограничение на ДЛИНУ имени снято, цифры разрешены; от
// неоднозначности защищает проверка префиксов, а не длина).
//
// ИМЯ КЛЮЧА в командной строке задаётся полностью или сокращённо:
// сокращение -- НЕПУСТОЙ ПРЕФИКС запрошенного имени: "-r" и "-re"
// соответствуют hasKey("realtime"), а "-rt" -- НЕТ (пропуски букв не
// допускаются; при необходимости коротких имён -- alias на прикладном
// уровне); регистр не различается ("-W" == "-w" == запросу "wind").
// НЕОДНОЗНАЧНОСТЬ СОКРАЩЕНИЙ проверяется САМИМ КЛАССОМ, если при
// инициализации передан полный список ключей (init с параметрами keys
// и nkeys). Тогда:
//   * список проверяется на коллизии -- ни один ключ не может быть
//     префиксом другого;
//   * каждое имя из командной строки должно быть префиксом НЕ БОЛЕЕ ЧЕМ
//     ОДНОГО ключа списка;
//   * каждое имя, передаваемое в hasKey/getKeyValue, проверяется так же.
// Любое нарушение -- АВАРИЙНОЕ ЗАВЕРШЕНИЕ с диагностикой в stderr:
// молчаливое срабатывание не того ключа обходится дороже остановки.
// Без списка (init с двумя параметрами) поведение прежнее: первое
// совпадение по порядку командной строки, проверок нет.
//
// ПОЗИЦИОННЫЕ аргументы нумеруются БЕЗ учёта ключей и их значений;
// индекс 0 -- самый первый аргумент (обычно имя исполняемого файла).
//
// Буферы значений: не короче CLI_VALUE_MAX; копия усекается с
// гарантированным нулём. Без STL и динамических аллокаций.
//============================================================================
#ifndef LIB_CLI_H
#define LIB_CLI_H

enum
{
    CLI_MAX_KEYS = 32,  // предел числа ключей в командной строке
    CLI_MAX_DEFS = 192, // предел числа объявленных ключей приложения (этап 121: 128 -> 192)
    CLI_MAX_POS = 32,   // предел числа позиционных аргументов
    CLI_VALUE_MAX = 128 // размер буфера значения (с нулём)
};

class Cli
{
public:
    Cli();
    Cli(int argc, char** argv);

    // Инициализация (повторная допустима)
    void init(int argc, char** argv);

    // Инициализация с ОБЪЯВЛЕННЫМ СПИСКОМ ключей приложения. Список не
    // копируется (время жизни -- статическая таблица вызывающего).
    // Проверяет список на коллизии и все имена из командной строки на
    // однозначность; при нарушении завершает задачу аварийно
    // fatalChecks = true (умолчание, прежнее поведение): нарушение списка
    // или строки -- аварийное завершение. false: список только объявляется,
    // а проверку выполняет verifyArgs -- она печатает ВСЕ нарушения и
    // возвращает признак, оставляя решение приложению (этап 119)
    void init(int argc, char** argv, const char* const* keys, int nkeys,
              bool fatalChecks = true);

    // Число объявленных ключей списка, которым имя name является
    // префиксом (без учёта регистра). 0 -- имя неизвестно, 1 -- имя
    // однозначно, >1 -- неоднозначно
    int matchCount(const char* name) const;

    // Наличие ключа (флажка); key -- полное имя, в строке допускается
    // сокращение-префикс, регистр не различается
    bool hasKey(const char* key) const;

    // Значение ключа в value (буфер >= CLI_VALUE_MAX); если ключ не
    // задан или без значения -- копируется def. Возврат: true --
    // значение взято из командной строки, false -- использован def
    bool getKeyValue(const char* key, char value[], const char* def = "") const;

    // ПРОВЕРКА КОМАНДНОЙ СТРОКИ (не завершает задачу): все ключи из
    // argv проверяются на ДОПУСТИМОСТЬ (имя должно быть префиксом ровно
    // одного объявленного ключа) и на ОТСУТСТВИЕ ПОВТОРОВ (два имени,
    // ведущие к одному объявленному ключу, -- повтор: "/wind" и "/wi").
    // Диагностика по каждому нарушению -- в stderr, ASCII. Возврат: true --
    // строка корректна. Требует объявленного списка ключей (init с keys);
    // без списка проверка невозможна -- возврат false с диагностикой.
    // verbose = false -- проверка без печати (для юнит-тестов и тихих
    // сценариев: диагностика в stderr на каждом прогоне -- лишний шум)
    bool verifyArgs(int argc, const char** argv, bool verbose = true) const;

    // Позиционный аргумент по индексу (ключи и их значения не
    // считаются; индекс 0 -- первый аргумент, обычно имя исполняемого
    // файла); буфер >= CLI_VALUE_MAX. Возврат: false -- индекса нет
    // (value получает пустую строку)
    bool getPosValue(int pos, char value[]) const;

    // ПРАВИЛО СООТВЕТСТВИЯ имён (публично -- для проверки допустимости
    // флагов прикладным слоем): имя name (как в строке) соответствует
    // полному имени key (см. контракт сокращений в шапке)
    static bool nameMatchesKey(const char* name, const char* key);

    // Число позиционных аргументов (включая индекс 0)
    int posCount() const
    {
        return m_nPos;
    }

    // Перечисление ключей (для проверки допустимости): число ключей и
    // имя ключа по индексу (как задан в строке, без маркера и '=');
    // буфер >= CLI_VALUE_MAX
    int keyCount() const
    {
        return m_nKeys;
    }
    bool getKeyName(int index, char name[]) const;

private:
    // --- объявленный список ключей приложения ---
    const char* const* m_defs; // таблица имён (не копируется) или 0
    int m_nDefs;               // число объявленных ключей

    // --- разобранный ключ ---
    struct Key
    {
        const char* name;  // начало имени (внутри argv)
        int nameLen;       // длина имени (до '=' или конца токена)
        const char* value; // значение (внутри argv) или 0
    };

    // Токен -- ключ ('-'/'/' + буква)
    static bool isKeyToken(const char* s);
    // Имя из строки (len символов) -- префикс запрошенного key
    // без учёта регистра
    static bool nameMatches(const char* name, int len, const char* key);
    // Копия строки в буфер значения с усечением
    static void copyValue(char dst[], const char* src);

    const Key* findKey(const char* key) const;

    // Проверка однозначности имени по объявленному списку; при
    // неоднозначности печатает диагностику и завершает задачу
    void requireUnambiguous(const char* name, const char* where) const;

    // --- разобранные аргументы (указатели в argv) ---
    Key m_keys[CLI_MAX_KEYS];       // ключи в порядке строки
    int m_nKeys;                    // число ключей
    const char* m_pos[CLI_MAX_POS]; // позиционные аргументы
    int m_nPos;                     // число позиционных
};

#endif // LIB_CLI_H
